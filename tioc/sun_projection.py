class TermType(Term_Model):
    """
    Term_s object sorted by their type:
    """
    terms: List[Term_s]
    nD: int  # Number of derivatives in the term.
    field_content: Dict
    mass_dim: int  # mass dimension
    # sun_projection_tensors:  # Sun_projection tensors
    def __init__(self, term : Term_s, nD : int, field_content: Dict):
        self.terms = [term]
        self.n_D = nD
        self.field_content = field_content
        self.mass_dim = term.coeff.dim_operator
        self.sun_projection_tensors = None

def get_type(terms):
    """
    Summands are sorted by their "type", i.e. field content and derivative.
    Parameters
    ----------
    terms
        Terms generated by converttoSL2C function.
    Returns
    -------
        Sorted terms.
    """
    logger.info("Sort fields by type, indicated by a tuple filled with integers. They specify the "
                "number of fields in the single summand in the following order: "
                f"{' '.join([field.name for field in model.fields.values()])}")
    single_terms = {}  # Ordered terms (by "type") with just a single term in it.
    for term in terms:
        for summand in term.terms:
            typ = summand.fieldcounter.values()
            if summand.coeff == "0":
                continue
            try:
                type(single_terms[tuple(typ)])
                try:
                    assert single_terms[tuple(typ)][summand.n_D].mass_dim == summand.coeff.dim_operator
                    single_terms[tuple(typ)][summand.n_D].terms.append(summand)
                except KeyError:
                    single_terms[tuple(typ)][summand.n_D] = TermType(summand, summand.n_D, summand.fieldcounter_stripped)
            except KeyError:
                single_terms[tuple(typ)] = {summand.n_D: TermType(summand, summand.n_D, summand.fieldcounter_stripped)}

    return single_terms

